package com.learn.m01_basics;

/*
 * ============================================================
 * 模块：m01 基础语法与基本类型
 * 关卡：Ex04 字面量的多种写法
 * ------------------------------------------------------------
 * 【知识点】
 *   “字面量”就是直接写在代码里的固定值。整数除了普通写法，还能：
 *     用下划线分隔提高可读性：1_000_000 等于 1000000
 *     用十六进制（0x 开头）：    0xFF 等于 255
 *     用二进制（0b 开头）：      0b1010 等于 10
 *   小数可用科学计数法：1.5e3 等于 1500.0
 *   字符可用 Unicode 转义：'A' 就是字母 'A'
 *
 * 【本关任务】
 *   用 TODO 指定的“写法”表示出对应的值。
 *
 * 【如何闯关】
 *   按提示改写每个占位值，运行 main，对照“预期输出”。
 * ============================================================
 */
public class Ex04_Literals {

    public static void main(String[] args) {

        // TODO(关卡4-1)：用下划线分隔写出一百万（1_000_000）
        int million = 0;

        // TODO(关卡4-2)：用十六进制写出 255（0xFF）
        int hex = 0;

        // TODO(关卡4-3)：用二进制写出 10（0b1010）
        int binary = 0;

        // TODO(关卡4-4)：用科学计数法写出 1500.0（1.5e3）
        double scientific = 0;

        // TODO(关卡4-5)：用 Unicode 转义写出字母 A（'A'）
        char unicode = ' ';

        System.out.println("一百万 = " + million);
        System.out.println("0xFF = " + hex);
        System.out.println("0b1010 = " + binary);
        System.out.println("1.5e3 = " + scientific);
        System.out.println("\\u0041 = " + unicode);
    }
}

