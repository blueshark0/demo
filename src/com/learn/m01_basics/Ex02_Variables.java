/*
 * ============================================================
 * 模块：m01 基础语法与基本类型
 * 关卡：Ex02 变量：给数据起个名字
 * ------------------------------------------------------------
 * 【知识点】
 *   变量是“存放数据的容器”。使用前要先声明，格式为：
 *       类型 变量名 = 值;
 *   例如  int score = 90;  声明了一个名为 score 的整数变量，值是 90。
 *   字符串类型是 String，值要用双引号括起来，例如 String s = "你好";
 *   用 + 可以把字符串和变量拼接起来一起打印。
 *
 * 【本关任务】
 *   1. 声明一个 int 变量 age，值为 18。
 *   2. 声明一个 String 变量 name，值为 "小明"。
 *
 * 【如何闯关】
 *   把下面两处 TODO 的占位值改成正确的值，运行 main，
 *   再对照文件底部“预期输出”。
 * ============================================================
 */
public class Ex02_Variables {

    public static void main(String[] args) {

        // TODO(关卡2-1)：把 0 改成 18，让 age 的值为 18
        int age = 0;

        // TODO(关卡2-2)：把空字符串改成 "小明"
        String name = "";

        // 下面两行负责打印，一般不需要你改动
        System.out.println("姓名：" + name);
        System.out.println("年龄：" + age);
    }
}

