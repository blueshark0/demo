package com.learn.m01_basics;

/*
 * ============================================================
 * 模块：m01 基础语法与基本类型
 * 关卡：Ex05 类型转换与精度丢失
 * ------------------------------------------------------------
 * 【知识点】
 *   不同类型之间可以互相转换，分两种情况：
 *     自动转换（小范围 → 大范围，安全）：例如把整数赋给小数类型，
 *       编译器会自动完成，不需要任何额外写法，也不会丢失数据。
 *     强制转换（大范围 → 小范围，可能丢失精度）：必须显式声明目标类型，
 *       而且小数转整数时是“截断”——直接砍掉小数部分，不是四舍五入。
 *
 * 【本关任务】
 *   下方已给定 int i = 7 与 double pi = 3.99（必须用这两个固定值，输出才能对上）。
 *   1. 把 int 变量 i 转换为 double，赋给已声明的变量 d。
 *   2. 把 double 变量 pi 转换为 int，赋给已声明的变量 truncated。
 *   程序据此打印：
 *       int 7 转 double = 7.0
 *       double 3.99 强制转 int = 3
 * ============================================================
 */
public class Ex05_TypeCasting {

    public static void main(String[] args) {

        int i = 7;
        // TODO(关卡5-1)：把 i 转换为 double 赋给 d
        double d = 0;

        double pi = 3.99;
        // TODO(关卡5-2)：把 pi 转换为 int 赋给 truncated
        int truncated = 0;

        System.out.println("int 7 转 double = " + d);
        System.out.println("double 3.99 强制转 int = " + truncated);
    }
}

