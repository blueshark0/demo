package com.learn.m14_commonapi;

import java.util.Random;

/*
 * ============================================================
 * 模块：m14 常用 API
 * 关卡：Ex04 随机数 Random
 * ------------------------------------------------------------
 * 【知识点】
 *   Random 用来生成随机数：
 *       random.nextInt(100)   生成 [0, 100) 之间的随机整数
 *   “种子”决定随机序列：相同的种子会生成完全相同的序列。本练习用
 *   固定种子 new Random(42)，所以每次运行结果都一样，方便对照预期输出。
 *   （真实项目通常用无参 new Random()，每次都不一样。）
 *
 * 【本关任务】
 *   连续生成并打印 3 个 [0, 100) 的随机整数。
 *
 * 【如何闯关】
 *   在循环里补一行打印 random.nextInt(100)，运行对照输出。
 * ============================================================
 */
public class Ex04_Random {

    public static void main(String[] args) {
        Random random = new Random(42); // 固定种子，保证结果可预期

        for (int i = 0; i < 3; i++) {
            // TODO(关卡4-1)：打印 random.nextInt(100)
            //   提示：System.out.println(random.nextInt(100));
        }
    }
}

