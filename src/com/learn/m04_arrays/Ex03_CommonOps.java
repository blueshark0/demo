package com.learn.m04_arrays;

import java.lang.reflect.Array;
import java.util.Arrays;

/*
 * ============================================================
 * 模块：m04 数组
 * 关卡：Ex03 求最值与排序
 * ------------------------------------------------------------
 * 【知识点】
 *   求数组最大值的常见思路：先假设第一个元素就是最大值，再遍历整个
 *   数组，每遇到一个比当前“最大值”更大的元素，就用它更新这个最大值；
 *   求最小值的思路完全对称。排序则不必自己手写，标准库的 Arrays
 *   工具类提供了现成的排序方法，能把数组原地从小到大排好；它还提供
 *   了把数组转成可读字符串的方法，方便整齐地打印出来。
 *
 * 【本关任务】
 *   下方给定数组 data = {5, 3, 9, 1, 7}（请保持不变）。请：
 *   1. 求出数组的最大值 max 与最小值 min。
 *   2. 把数组从小到大排序。
 *   使程序打印：
 *       最大值 = 9
 *       最小值 = 1
 *       排序后 = [1, 3, 5, 7, 9]
 * ============================================================
 */
public class Ex03_CommonOps {

    public static void main(String[] args) {
        int[] data = {5, 3, 9, 1, 7};

        int max = data[0];
        for (int v : data) {
            // TODO(关卡3-1)：如果 v 比当前 max 大，就用 v 更新 max
            max = v > max ? v : max;

        }

        int min = data[0];
        for (int v : data) {
            // TODO(关卡3-2)：如果 v 比当前 min 小，就用 v 更新 min
            min = v < min ? v : min;
        }

        // TODO(关卡3-3)：用 Arrays 工具类把 data 从小到大原地排序
        Arrays.sort(data);

        System.out.println("最大值 = " + max);
        System.out.println("最小值 = " + min);
        System.out.println("排序后 = " + Arrays.toString(data));
    }
}

