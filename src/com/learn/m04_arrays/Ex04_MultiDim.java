package com.learn.m04_arrays;

/*
 * ============================================================
 * 模块：m04 数组
 * 关卡：Ex04 二维数组
 * ------------------------------------------------------------
 * 【知识点】
 *   二维数组可以理解为“表格”（行 × 列），本质是“数组的数组”：
 *       int[][] matrix = { {1, 2, 3}, {4, 5, 6} };  // 2 行 3 列
 *   matrix.length 是行数；matrix[r].length 是第 r 行的列数。
 *   遍历用双重循环：外层走行，内层走列。
 *
 * 【本关任务】
 *   按“行”打印矩阵：每行的元素用空格分隔，每行结束换行。
 *
 * 【如何闯关】
 *   在内层循环体里补一行打印语句，运行对照输出。
 * ============================================================
 */
public class Ex04_MultiDim {

    public static void main(String[] args) {
        int[][] matrix = {
                {1, 2, 3},
                {4, 5, 6}
        };

        for (int r = 0; r < matrix.length; r++) {
            for (int c = 0; c < matrix[r].length; c++) {
                // TODO(关卡4-1)：打印 matrix[r][c] 再跟一个空格（不换行）
                System.out.print(matrix[r][c] + " ");
                //   提示：System.out.print(matrix[r][c] + " ");
            }
            System.out.println(); // 每行结束后换行
        }
    }
}

