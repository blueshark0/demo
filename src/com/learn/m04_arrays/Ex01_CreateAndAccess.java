package com.learn.m04_arrays;

/*
 * ============================================================
 * 模块：m04 数组
 * 关卡：Ex01 创建数组与下标访问
 * ------------------------------------------------------------
 * 【知识点】
 *   数组是一段能装“固定个数、同类型”元素的连续空间。创建时要指定
 *   长度，新建后每个元素都有默认值（int 数组默认是 0）。访问元素靠
 *   “下标”，下标从 0 开始，第 1 个元素的下标是 0，依此类推；通过
 *   下标既能读取某个元素，也能给它赋值。数组还能告诉你它的长度，
 *   而最大的合法下标永远是“长度减一”，越界访问会抛异常。
 *
 * 【本关任务】
 *   下方已创建一个长度为 3 的 int 数组 nums。请给它的三个元素
 *   分别赋值：第 1 个为 10、第 2 个为 20、第 3 个为 30，使程序打印：
 *       长度 = 3
 *       nums[0] = 10
 *       nums[1] = 20
 *       nums[2] = 30
 * ============================================================
 */
public class Ex01_CreateAndAccess {

    public static void main(String[] args) {
        int[] nums = new int[3];
        // TODO(关卡1-1)：给 nums  1 个元素赋值 10
        nums[0] = 10;
        // TODO(关卡1-2)：给 nums 的第 2 个元素赋值 20
        nums[1] = 20;

        // TODO(关卡1-3)：给 nums 的第 3 个元素赋值 30
        nums[2] = 30;


        System.out.println("长度 = " + nums.length);
        System.out.println("nums[0] = " + nums[0]);
        System.out.println("nums[1] = " + nums[1]);
        System.out.println("nums[2] = " + nums[2]);
    }
}

