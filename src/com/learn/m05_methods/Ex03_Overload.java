package com.learn.m05_methods;

/*
 * ============================================================
 * 模块：m05 方法
 * 关卡：Ex03 方法重载
 * ------------------------------------------------------------
 * 【知识点】
 *   “重载”指：多个方法名字相同，但参数不同（个数或类型不同），可以
 *   并存于同一个类里。调用时，编译器会根据你传入的实参类型，自动挑选
 *   出最匹配的那个方法去执行。这样同一个名字就能对不同类型的数据做
 *   相似的事，调用起来更顺手。注意：仅返回值类型不同、参数完全一样，
 *   是不能构成重载的。
 *
 * 【本关任务】
 *   实现两个名为 add 的方法：一个接收两个 int 参数，一个接收两个 double
 *   参数，各自返回它们的和。main 会分别调用，期望打印「int  版：5」与
 *  「double 版：6.0」（double 的结果带小数点）。
 * ============================================================
 */
public class Ex03_Overload {

    static int add(int a, int b) {
        // TODO(关卡3-1)：返回两个 int 的和
        return a + b ;

    }

    static double add(double a, double b) {
        // TODO(关卡3-2)：返回两个 double 的和
        return a + b ;

    }

    public static void main(String[] args) {
        System.out.println("int  版：" + add(2, 3));
        System.out.println("double 版：" + add(2.5, 3.5));
    }
}

/*
 * ============================ 预期输出 ============================
 * int  版：5
 * double 版：6.0
 * ===============================================================
 *
 * 排查提示：
 *  - 运行时若抛出 UnsupportedOperationException，说明方法体还没补全。
 *  - 两个方法名都叫 add，靠参数类型（int 还是 double）来区分。
 *  - double 版结果是 6.0（带小数点），int 版是 5。
 */
