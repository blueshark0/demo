package com.learn.m05_methods;

/*
 * ============================================================
 * 模块：m05 方法
 * 关卡：Ex04 递归
 * ------------------------------------------------------------
 * 【知识点】
 *   递归 = 方法在自己内部又调用自己，把大问题拆成更小的同类问题。
 *   以阶乘为例：n! = n × (n-1) × ... × 1，本质上 n! 就等于 n 乘以
 *  (n-1)! ——也就是把同一个问题缩小一层再交给自己去算。递归必须有一个
 *   “终止条件”（也叫递归出口）来停止下钻，否则会无限递归直到栈溢出。
 *
 * 【本关任务】
 *   用递归实现 factorial(n)，计算 n 的阶乘。
 *   main 会调用 factorial(5)，期望打印「5! = 120」。
 * ============================================================
 */
public class Ex04_Recursion {

    static long factorial(int n) {
        // TODO(关卡4-1)：用递归返回 n!（记得先写终止条件，再让方法调用自己缩小问题）
        if (n <= 1) {
            return 1;
        }
        return n * factorial(n -1);

    }

    public static void main(String[] args) {
        System.out.println("5! = " + factorial(5));
    }
}

/*
 * ============================ 预期输出 ============================
 * 5! = 120
 * ===============================================================
 *
 * 排查提示：
 *  - 运行时若抛出 UnsupportedOperationException，说明方法体还没补全。
 *  - 5! = 5×4×3×2×1 = 120。
 *  - 千万别忘了终止条件，否则会一直递归到崩溃。
 *  - 用 long 而不是 int，是因为阶乘增长极快，int 容易装不下。
 */
