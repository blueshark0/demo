package com.learn.m05_methods;

/*
 * ============================================================
 * 模块：m05 方法
 * 关卡：Ex01 定义并调用方法
 * ------------------------------------------------------------
 * 【知识点】
 *   方法是一段可以反复调用的代码。最简单的方法没有输入也没有输出：
 *       static void greet() {
 *           System.out.println("...");
 *       }
 *   void 表示“没有返回值”。在 main 里写 greet(); 就能“调用”它。
 *   定义一次，可以调用很多次。
 *
 * 【本关任务】
 *   实现 greet() 方法，让它打印一行：大家好，我是方法！
 *
 * 【如何闯关】
 *   把 greet() 里那行 throw 替换成正确的打印语句，运行对照输出。
 * ============================================================
 */
public class Ex01_DefineAndCall {

    static void greet() {
        // TODO(关卡1-1)：让本方法打印一行 “大家好，我是方法！”
        // 提示：用 System.out.println(...)，然后删掉下面这行 throw
        System.out.println("大家好，我是方法!");
    }

    public static void main(String[] args) {
        // main 调用 greet() 两次，体会“定义一次、反复调用”
        greet();
        greet();
    }
}

