package com.learn.m05_methods;

/*
 * ============================================================
 * 模块：m05 方法
 * 关卡：Ex01 定义并调用方法
 * ------------------------------------------------------------
 * 【知识点】
 *   方法是一段可以反复调用的代码，定义一次后就能在很多地方使用。
 *   最简单的方法既没有输入（参数），也没有输出（返回值）——这种
 *   “没有返回值”的方法，返回值类型写作 void。把方法定义好后，在
 *   别处“调用”它，就会执行方法里那段代码；调用多少次就执行多少次。
 *
 * 【本关任务】
 *   实现 greet() 方法，让它打印一行：大家好，我是方法！
 *   main 里已经调用了 greet() 两次，所以最终应打印两行相同的内容。
 * ============================================================
 */
public class Ex01_DefineAndCall {

    static void greet() {
        // TODO(关卡1-1)：让本方法打印一行 “大家好，我是方法！”
        System.out.println("大家好，我是方法！");
    }

    public static void main(String[] args) {
        // main 调用 greet() 两次，体会“定义一次、反复调用”
        greet();
        greet();
    }
}

