package com.learn.m06_strings;

/*
 * ============================================================
 * 模块：m06 String 字符串
 * 关卡：Ex05 格式化
 * ------------------------------------------------------------
 * 【知识点】
 *   String.format 用“占位符”生成格式化字符串：先写一个带占位符的
 *   模板，再按顺序提供要填进去的值，占位符和后面的参数一一对应。
 *   常用占位符：字符串占位、整数占位、小数占位，其中小数占位还能
 *   指定保留几位小数（会自动四舍五入）。
 *
 * 【本关任务】
 *   下方已给定 name = "小明"、age = 18、price = 3.14159
 *   （必须用这三个固定值，输出才能对上）。请：
 *   1. 用 String.format 配合模板「姓名：%s，年龄：%d」，把 name、age
 *      作为参数填进去，赋给 info，使其打印「姓名：小明，年龄：18」。
 *   2. 用 String.format 配合模板「价格：%.2f」，把 price 作为参数填进去
 *      （保留两位小数），赋给 priceStr，使其打印「价格：3.14」。
 * ============================================================
 */
public class Ex05_Format {

    public static void main(String[] args) {
        String name = "小明";
        int age = 18;

        // TODO(关卡5-1)：用模板「姓名：%s，年龄：%d」把 name、age 填进去，赋给 info
        String info = String.format("姓名：%s，年龄：%d ", name , age);

        double price = 3.14159;
        // TODO(关卡5-2)：用模板「价格：%.2f」把 price 填进去（保留两位小数），赋给 priceStr
        String priceStr = String.format("价格：%.2f",price);

        System.out.println(info);
        System.out.println(priceStr);
    }
}

/*
 * ============================ 预期输出 ============================
 * 姓名：小明，年龄：18
 * 价格：3.14
 * ===============================================================
 *
 * 排查提示：
 *  - 保留两位小数时，3.14159 会被四舍五入成 3.14。
 *  - 占位符的个数和顺序，要和后面的参数一一对应。
 */
