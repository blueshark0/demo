package com.learn.m06_strings;

/*
 * ============================================================
 * 模块：m06 String 字符串
 * 关卡：Ex05 格式化
 * ------------------------------------------------------------
 * 【知识点】
 *   String.format 用“占位符”生成格式化字符串，常用占位符：
 *       %s  字符串    %d  整数    %f  小数    %.2f 保留两位小数
 *   例如： String.format("姓名：%s，年龄：%d", "小明", 18)
 *          得到  "姓名：小明，年龄：18"
 *   占位符按顺序与后面的参数一一对应。
 *
 * 【本关任务】
 *   1. 把 name、age 作为参数，填进第一个 format。
 *   2. 把 price 作为参数，保留两位小数。
 *
 * 【如何闯关】
 *   把占位参数（"占位" 和 0、0.0）改成正确的变量，运行对照输出。
 * ============================================================
 */
public class Ex05_Format {

    public static void main(String[] args) {
        String name = "小明";
        int age = 18;

        // TODO(关卡5-1)：把 "占位" 改成 name，把 0 改成 age
        String info = String.format("姓名：%s，年龄：%d", "占位", 0);

        double price = 3.14159;
        // TODO(关卡5-2)：把 0.0 改成 price（%.2f 会保留两位小数）
        String priceStr = String.format("价格：%.2f", 0.0);

        System.out.println(info);
        System.out.println(priceStr);
    }
}

