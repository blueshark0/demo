package com.learn.m02_operators;

/*
 * ============================================================
 * 模块：m02 运算符
 * 关卡：Ex05 三元运算符与自增自减
 * ------------------------------------------------------------
 * 【知识点】
 *   三元运算符：  条件 ? 值1 : 值2
 *       条件成立取值1，否则取值2。例如 a > b ? a : b 取较大值。
 *   自增自减：++ 让变量加 1，-- 让变量减 1。位置不同含义不同：
 *       i++（后自增）：先用 i 当前的值，之后 i 再加 1
 *       ++i（前自增）：i 先加 1，再用加完之后的值
 *
 * 【本关任务】
 *   1. 用三元运算符求 a、b 的较大值。
 *   2. 体会 i++（后自增）与 ++m（前自增）的区别。
 *
 * 【如何闯关】
 *   把占位 0 改成 TODO 要求的表达式，运行对照输出。
 * ============================================================
 */
public class Ex05_TernaryAndIncrement {

    public static void main(String[] args) {
        int a = 8;
        int b = 5;

        // TODO(关卡5-1)：把 0 改成 (a > b ? a : b)，求较大值
        int max = 0;

        int i = 10;
        // TODO(关卡5-2)：把 0 改成 i++（先取值赋给 j，之后 i 自己变 11）
        int j = 0;

        int m = 10;
        // TODO(关卡5-3)：把 0 改成 ++m（m 先变 11，再把 11 赋给 n）
        int n = 0;

        System.out.println("较大值 = " + max);
        System.out.println("i++ 之后：j = " + j + ", i = " + i);
        System.out.println("++m 之后：n = " + n + ", m = " + m);
    }
}

