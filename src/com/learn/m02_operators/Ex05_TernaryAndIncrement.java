package com.learn.m02_operators;

/*
 * ============================================================
 * 模块：m02 运算符
 * 关卡：Ex05 三元运算符与自增自减
 * ------------------------------------------------------------
 * 【知识点】
 *   三元运算符：根据一个布尔条件在两个值之间二选一——条件成立取前一个值，
 *   否则取后一个值。它能把“如果……否则……”浓缩成一行表达式。
 *   自增自减：让变量加 1 或减 1。写在变量后面（后自增）与写在变量前面
 *   （前自增）含义不同：
 *       后自增：先取变量“当前的值”参与运算，之后变量本身再加 1
 *       前自增：变量先加 1，再用“加完之后的新值”参与运算
 *
 * 【本关任务】
 *   下方已给定 a = 8、b = 5，以及 i = 10、m = 10（必须用这些固定值）。
 *   请完成：
 *     1. 用三元运算符取 a、b 中的较大值，赋给 max。
 *     2. 用后自增：把 i 当前的值赋给 j，使 i 随后变为 11。
 *     3. 用前自增：让 m 先加 1，再把新值赋给 n。
 *   使程序打印出：
 *       较大值 = 8
 *       i++ 之后：j = 10, i = 11
 *       ++m 之后：n = 11, m = 11
 * ============================================================
 */
public class Ex05_TernaryAndIncrement {

    public static void main(String[] args) {
        int a = 8;
        int b = 5;

        // TODO(关卡5-1)：用三元运算符取 a、b 中的较大值，赋给 max
        int max = a > b ? a : b;

        int i = 10;
        // TODO(关卡5-2)：用后自增，把 i 当前的值赋给 j（之后 i 自己变成 11）
        int j = i++;

        int m = 10;
        // TODO(关卡5-3)：用前自增，让 m 先变 11，再把这个新值赋给 n
        int n = ++m;

        System.out.println("较大值 = " + max);
        System.out.println("i++ 之后：j = " + j + ", i = " + i);
        System.out.println("++m 之后：n = " + n + ", m = " + m);
    }
}

