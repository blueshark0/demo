package com.learn.m02_operators;

/*
 * ============================================================
 * 模块：m02 运算符
 * 关卡：Ex04 位运算符
 * ------------------------------------------------------------
 * 【知识点】
 *   位运算直接对整数的二进制位操作。以 6（二进制 0110）和 3（0011）为例：
 *       &（按位与）：对应位都为 1 才得 1   → 6 & 3 = 0010 = 2
 *       |（按位或）：对应位有一个 1 就得 1 → 6 | 3 = 0111 = 7
 *       ^（按位异或）：对应位不同才得 1   → 6 ^ 3 = 0101 = 5
 *       ~（按位取反）：每一位翻转          → ~6 = -7
 *       <<（左移）：整体左移，相当于乘 2   → 6 << 1 = 12
 *       >>（右移）：整体右移，相当于除 2   → 6 >> 1 = 3
 *
 * 【本关任务】
 *   用 a、b 写出 6 个位运算表达式。
 *
 * 【如何闯关】
 *   把占位 0 改成 TODO 要求的位运算表达式，运行对照输出。
 * ============================================================
 */
public class Ex04_Bitwise {

    public static void main(String[] args) {
        int a = 6;
        int b = 3;

        // TODO(关卡4-1)：把 0 改成 a & b
        int and = a & b;
        // TODO(关卡4-2)：把 0 改成 a | b
        int or = a | b;
        // TODO(关卡4-3)：把 0 改成 a ^ b
        int xor = a ^ b;
        // TODO(关卡4-4)：把 0 改成 ~a
        int not = ~a;
        // TODO(关卡4-5)：把 0 改成 a << 1
        int shiftLeft = a << 1;
        // TODO(关卡4-6)：把 0 改成 a >> 1
        int shiftRight = a >> 1;

        System.out.println("6 & 3 = " + and);
        System.out.println("6 | 3 = " + or);
        System.out.println("6 ^ 3 = " + xor);
        System.out.println("~6 = " + not);
        System.out.println("6 << 1 = " + shiftLeft);
        System.out.println("6 >> 1 = " + shiftRight);
    }
}

