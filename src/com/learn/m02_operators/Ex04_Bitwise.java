package com.learn.m02_operators;

/*
 * ============================================================
 * 模块：m02 运算符
 * 关卡：Ex04 位运算符
 * ------------------------------------------------------------
 * 【知识点】
 *   位运算直接对整数的二进制位进行操作：
 *       按位与：两个数对应的二进制位都为 1 时，该位才得 1
 *       按位或：两个数对应位只要有一个为 1，该位就得 1
 *       按位异或：两个数对应位不同（一个 1 一个 0）才得 1
 *       按位取反：把每一位 0/1 翻转
 *       左移：把二进制位整体向左移动若干位，效果约等于乘 2 的幂
 *       右移：把二进制位整体向右移动若干位，效果约等于除以 2 的幂
 *
 * 【本关任务】
 *   下方已给定 a = 6、b = 3（必须用这两个固定值）。
 *   请写出 6 个位运算表达式，分别赋给 and、or、xor、not、shiftLeft、shiftRight：
 *     - and：a 按位与 b
 *     - or：a 按位或 b
 *     - xor：a 按位异或 b
 *     - not：对 a 按位取反
 *     - shiftLeft：把 a 左移 1 位
 *     - shiftRight：把 a 右移 1 位
 *   使程序打印出：
 *       6 & 3 = 2
 *       6 | 3 = 7
 *       6 ^ 3 = 5
 *       ~6 = -7
 *       6 << 1 = 12
 *       6 >> 1 = 3
 * ============================================================
 */
public class Ex04_Bitwise {

    public static void main(String[] args) {
        int a = 6;
        int b = 3;

        // TODO(关卡4-1)：a 按位与 b，结果赋给 and
        int and = a&b;
        // TODO(关卡4-2)：a 按位或 b，结果赋给 or
        int or = a|b;
        // TODO(关卡4-3)：a 按位异或 b，结果赋给 xor
        int xor = a^b;
        // TODO(关卡4-4)：对 a 按位取反，结果赋给 not
        int not = ~a;
        // TODO(关卡4-5)：把 a 左移 1 位，结果赋给 shiftLeft
        int shiftLeft = a<<1;
        // TODO(关卡4-6)：把 a 右移 1 位，结果赋给 shiftRight
        int shiftRight = a>>1;

        System.out.println("6 & 3 = " + and);
        System.out.println("6 | 3 = " + or);
        System.out.println("6 ^ 3 = " + xor);
        System.out.println("~6 = " + not);
        System.out.println("6 << 1 = " + shiftLeft);
        System.out.println("6 >> 1 = " + shiftRight);
    }
}

