package com.learn.m02_operators;

/*
 * ============================================================
 * 模块：m02 运算符
 * 关卡：Ex01 算术运算符
 * ------------------------------------------------------------
 * 【知识点】
 *   算术运算符： +（加） -（减） *（乘） /（除） %（取余）。
 *   特别注意：两个整数相除，结果只保留整数部分（直接砍掉小数）！
 *       17 / 5 = 3   （不是 3.4）
 *   取余 % 得到的是“除不尽剩下的部分”：
 *       17 % 5 = 2   （17 = 5*3 + 2）
 *
 * 【本关任务】
 *   用变量 a、b 算出 和、差、积、商、余 五个结果。
 *
 * 【如何闯关】
 *   把每个占位值 0 改成 TODO 要求的表达式，运行对照“预期输出”。
 * ============================================================
 */
public class Ex01_Arithmetic {

    public static void main(String[] args) {
        int a = 17;
        int b = 5;

        // TODO(关卡1-1)：把 0 改成 a + b
        int sum = a + b;
        // TODO(关卡1-2)：把 0 改成 a - b
        int diff = a - b;
        // TODO(关卡1-3)：把 0 改成 a * b
        int product = a * b;
        // TODO(关卡1-4)：把 0 改成 a / b（整数除法）
        int quotient = a / b;
        // TODO(关卡1-5)：把 0 改成 a % b（取余）
        int remainder = a % b;

        System.out.println("17 + 5 = " + sum);
        System.out.println("17 - 5 = " + diff);
        System.out.println("17 * 5 = " + product);
        System.out.println("17 / 5 = " + quotient);
        System.out.println("17 % 5 = " + remainder);
    }
}

