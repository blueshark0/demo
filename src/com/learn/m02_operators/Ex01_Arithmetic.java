package com.learn.m02_operators;

/*
 * ============================================================
 * 模块：m02 运算符
 * 关卡：Ex01 算术运算符
 * ------------------------------------------------------------
 * 【知识点】
 *   算术运算符： +（加） -（减） *（乘） /（除） %（取余）。
 *   特别注意：两个整数相除，结果只保留整数部分（直接砍掉小数），
 *   不会四舍五入，也不会得到小数。
 *   取余 % 得到的是“除不尽剩下的部分”：被除数减去“整除部分”后剩下的余数。
 *
 * 【本关任务】
 *   下方已给定两个整数 a = 17、b = 5（必须用这两个固定值，输出才能对上）。
 *   请分别算出它们的 和、差、积、商、余 五个结果，并赋给已声明的变量
 *   sum、diff、product、quotient、remainder，使程序打印出：
 *       17 + 5 = 22
 *       17 - 5 = 12
 *       17 * 5 = 85
 *       17 / 5 = 3
 *       17 % 5 = 2
 *   注意：商是整数除法的结果，余是取余的结果。
 * ============================================================
 */
public class Ex01_Arithmetic {

    public static void main(String[] args) {
        int a = 17;
        int b = 5;

        // TODO(关卡1-1)：算出 a 与 b 的和，赋给 sum
        int sum = a+b;
        // TODO(关卡1-2)：算出 a 与 b 的差，赋给 diff
        int diff = a-b;
        // TODO(关卡1-3)：算出 a 与 b 的积，赋给 product
        int product = a*b;
        // TODO(关卡1-4)：算出 a 除以 b 的商（整数除法），赋给 quotient
        int quotient = a/b;
        // TODO(关卡1-5)：算出 a 除以 b 的余数（取余），赋给 remainder
        int remainder = a%b;

        System.out.println("17 + 5 = " + sum);
        System.out.println("17 - 5 = " + diff);
        System.out.println("17 * 5 = " + product);
        System.out.println("17 / 5 = " + quotient);
        System.out.println("17 % 5 = " + remainder);
    }
}

