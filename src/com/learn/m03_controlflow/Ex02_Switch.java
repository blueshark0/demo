package com.learn.m03_controlflow;

/*
 * ============================================================
 * 模块：m03 控制流
 * 关卡：Ex02 switch 多值匹配
 * ------------------------------------------------------------
 * 【知识点】
 *   当要根据“一个变量的不同取值”做不同处理时，switch 比一堆 if 更清晰。
 *   Java 较新的“箭头写法”很直观（不需要写 break）：
 *       String s = switch (x) {
 *           case 1 -> "一";
 *           case 2 -> "二";
 *           default -> "其它";
 *       };
 *
 * 【本关任务】
 *   把 day（1~7）映射成中文星期。这里 day = 3，请把 case 3 的占位
 *   文字改成正确的 "周三"。
 *
 * 【如何闯关】
 *   修改 TODO 处的字符串，运行对照输出。
 * ============================================================
 */
public class Ex02_Switch {

    public static void main(String[] args) {
        int day = 3;

        String name = switch (day) {
            case 1 -> "周一";
            case 2 -> "周二";
            // TODO(关卡2-1)：把下面的占位文字改成 "周三"
            case 3 -> "周三";
            case 4 -> "周四";
            case 5 -> "周五";
            case 6 -> "周六";
            case 7 -> "周日";
            default -> "无效";
        };

        System.out.println("第 " + day + " 天是 " + name);
    }
}

