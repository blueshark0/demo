/*
 * ============================================================
 * 模块：m03 控制流
 * 关卡：Ex01 if / else if / else 分支
 * ------------------------------------------------------------
 * 【知识点】
 *   if 根据条件决定是否执行一段代码。多个条件可以用 else if 串联，
 *   都不满足时走 else。程序会从上往下逐个检查，命中第一个成立的
 *   分支后就不再看后面的，因此条件的先后顺序会影响结果。
 *
 * 【本关任务】
 *   给 score 评级：>=90 评「优秀」，>=80 评「良好」，>=60 评「及格」，
 *   否则评「不及格」。这里 score = 75（这个值不要改），请补全中间
 *   两个 else if 分支的判断条件，让最终打印「分数 75 的等级是：及格」。
 * ============================================================
 */
public class Ex01_IfElse {

    public static void main(String[] args) {
        int score = 75;
        String grade;

        if (score >= 90) {
            grade = "优秀";
        // TODO(关卡1-1)：补全此处的 else if 判断条件，对应「良好」这一档
        } else if (false) {
            grade = "良好";
        // TODO(关卡1-2)：补全此处的 else if 判断条件，对应「及格」这一档
        } else if (false) {
            grade = "及格";
        } else {
            grade = "不及格";
        }

        System.out.println("分数 " + score + " 的等级是：" + grade);
    }
}

