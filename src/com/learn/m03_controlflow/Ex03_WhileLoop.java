package com.learn.m03_controlflow;

/*
 * ============================================================
 * 模块：m03 控制流
 * 关卡：Ex03 while 循环
 * ------------------------------------------------------------
 * 【知识点】
 *   while 在“条件成立”时反复执行循环体，直到条件不再成立：
 *       while (条件) {
 *           // 反复执行的代码
 *       }
 *   循环里一定要有能让条件“最终变为 false”的语句（这里是 i++），
 *   否则会死循环。
 *
 * 【本关任务】
 *   用 while 累加 1 + 2 + 3 + ... + 100，结果存进 sum。
 *   循环条件 i <= n 已经写好了，你只需在循环体里补上“累加”那一步。
 *
 * 【如何闯关】
 *   在循环体里补一行把 i 累加到 sum 的语句，运行对照输出。
 * ============================================================
 */
public class Ex03_WhileLoop {

    public static void main(String[] args) {
        int n = 100;
        int sum = 0;
        int i = 1;

        while (i <= n) {
            // TODO(关卡3-1)：把当前的 i 累加到 sum
            //   提示：sum += i;
            sum = sum + i;
            i++; // i 每次加 1，最终超过 n 让循环结束
        }

        System.out.println("1 + 2 + ... + 100 = " + sum);
    }
}

