package com.learn.m03_controlflow;

/*
 * ============================================================
 * 模块：m03 控制流
 * 关卡：Ex03 while 循环
 * ------------------------------------------------------------
 * 【知识点】
 *   while 在“条件成立”时反复执行循环体，直到条件不再成立。
 *   循环里一定要有能让条件“最终变为 false”的语句（否则会死循环），
 *   每跑一圈都要朝着“让条件变为 false”的方向前进一步。
 *
 * 【本关任务】
 *   用 while 累加 1 + 2 + 3 + ... + 100，把累加结果存进变量 sum，
 *   最终打印「1 + 2 + ... + 100 = 5050」。
 *   循环条件 i <= n 与让 i 前进的 i++ 都已给好，你需要在循环体里
 *   补上“把当前的 i 累加进 sum”这一步。
 * ============================================================
 */
public class Ex03_WhileLoop {

    public static void main(String[] args) {
        int n = 100;
        int sum = 0;
        int i = 1;

        while (i <= n) {
            // TODO(关卡3-1)：把当前的 i 累加到 sum
            sum = sum + i;
            i++; // i 每次加 1，最终超过 n 让循环结束
        }

        System.out.println("1 + 2 + ... + 100 = " + sum);
    }
}

