package com.learn.m03_controlflow;

/*
 * ============================================================
 * 模块：m03 控制流
 * 关卡：Ex05 break / continue 与嵌套循环
 * ------------------------------------------------------------
 * 【知识点】
 *   break：立刻跳出当前循环。continue：跳过本次剩余代码，进入下一次。
 *   循环可以嵌套（循环里再套循环）。普通 break 只能跳出“最里层”循环，
 *   想一次跳出多层，可以给外层循环起个“标签”，用 break 标签名：
 *       outer:
 *       for (...) {
 *           for (...) {
 *               if (...) break outer; // 直接跳出 outer 这层
 *           }
 *       }
 *
 * 【本关任务】
 *   在 1~9 的两个数 i、j 中，按 i、j 从小到大找出“乘积等于 12 的第一对”，
 *   找到后用带标签的 break 立刻跳出双重循环。
 *
 * 【如何闯关】
 *   把占位条件 false 改成 i * j == 12，运行对照输出。
 * ============================================================
 */
public class Ex05_BreakContinueNested {

    public static void main(String[] args) {
        int foundI = -1;
        int foundJ = -1;

        outer:
        for (int i = 1; i <= 9; i++) {
            for (int j = 1; j <= 9; j++) {
                // TODO(关卡5-1)：把 false 改成 i * j == 12
                if (false) {
                    foundI = i;
                    foundJ = j;
                    break outer; // 找到第一对就跳出两层循环
                }
            }
        }

        System.out.println("第一对乘积为 12 的是 " + foundI + " × " + foundJ);
    }
}

