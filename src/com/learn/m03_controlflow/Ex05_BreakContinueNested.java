package com.learn.m03_controlflow;

/*
 * ============================================================
 * 模块：m03 控制流
 * 关卡：Ex05 break / continue 与嵌套循环
 * ------------------------------------------------------------
 * 【知识点】
 *   break：立刻跳出当前循环。continue：跳过本次剩余代码，进入下一次。
 *   循环可以嵌套（循环里再套循环）。普通 break 只能跳出“最里层”循环；
 *   想一次跳出多层，可以给某一层循环起个“标签”，再让 break 指明
 *   要跳出的是哪一层，这样命中条件时能一次性退出整个嵌套。
 *
 * 【本关任务】
 *   在 1~9 的两个数 i、j 中，按 i、j 从小到大找出“乘积等于 12 的第一对”，
 *   找到后把 i、j 分别记到 foundI、foundJ，并立刻跳出整个双重循环，
 *   最终打印「第一对乘积为 12 的是 2 × 6」。
 *   两个 for 循环头与外层标签 outer 都已给好，循环体内的逻辑由你补全。
 * ============================================================
 */
public class Ex05_BreakContinueNested {

    public static void main(String[] args) {
        int foundI = -1;
        int foundJ = -1;

        outer:
        for (int i = 1; i <= 9; i++) {
            for (int j = 1; j <= 9; j++) {
                // TODO(关卡5-1)：判断 i 与 j 的乘积是否等于 12；若相等，
                if(i * j == 12) {
                    foundI = i;
                    foundJ = j;
                    break outer;
                }
                //               把 i、j 记到 foundI、foundJ，并用带标签的 break
                //               一次跳出外层 outer 循环

            }
        }

        System.out.println("第一对乘积为 12 的是 " + foundI + " × " + foundJ);
    }
}

