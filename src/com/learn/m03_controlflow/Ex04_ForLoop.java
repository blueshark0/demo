package com.learn.m03_controlflow;

/*
 * ============================================================
 * 模块：m03 控制流
 * 关卡：Ex04 for 循环
 * ------------------------------------------------------------
 * 【知识点】
 *   for 循环把“初始化、条件、步进”三件事写在一行，适合循环固定次数。
 *   print 与 println 类似，但打印后“不换行”，所以同一行可以连续输出
 *   多段内容；字符串拼接里若混入算术运算，要注意运算与拼接的先后。
 *
 * 【本关任务】
 *   用 for 打印 7 的乘法口诀一整行（不换行），最终输出：
 *       7x1=7 7x2=14 7x3=21 7x4=28 7x5=35 7x6=42 7x7=49 7x8=56 7x9=63
 *   注意：每个算式后面紧跟一个空格；算式形如「7x列=积」，
 *   其中 7 来自 row，列来自循环变量 col，积是两者相乘。
 *   循环头 for (int col = 1; col <= 9; col++) 已给好，循环结束后已为你换行。
 * ============================================================
 */
public class Ex04_ForLoop {

    public static void main(String[] args) {
        int row = 7;

        for (int col = 1; col <= 9; col++) {
            // TODO(关卡4-1)：打印当前的算式「row x col = 积」，末尾带一个空格，且不换行
            System.out.print(row + "x" + col + "=" + row * col + " ");
        }
        System.out.println(); // 循环结束后换行
    }
}

