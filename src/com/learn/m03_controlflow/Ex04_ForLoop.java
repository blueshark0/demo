package com.learn.m03_controlflow;

/*
 * ============================================================
 * 模块：m03 控制流
 * 关卡：Ex04 for 循环
 * ------------------------------------------------------------
 * 【知识点】
 *   for 循环把“初始化、条件、步进”写在一行，适合循环固定次数：
 *       for (int k = 1; k <= 9; k++) {
 *           // 循环体
 *       }
 *   System.out.print(...) 与 println 类似，但打印后“不换行”。
 *
 * 【本关任务】
 *   打印 7 的乘法口诀一整行：7x1=7 7x2=14 ... 7x9=63
 *   （每个算式后面跟一个空格）
 *
 * 【如何闯关】
 *   在循环体里补一行 print 语句，运行对照输出。
 * ============================================================
 */
public class Ex04_ForLoop {

    public static void main(String[] args) {
        int row = 7;

        for (int col = 1; col <= 9; col++) {
            System.out.print(row + "x" + col + "=" + row * col + " ");
            // TODO(关卡4-1)：打印 "7x1=7 " 这样的算式（末尾带一个空格，不换行）
            //   提示：System.out.print(row + "x" + col + "=" + (row * col) + " ");
        }
        System.out.println(); // 循环结束后换行
    }
}

