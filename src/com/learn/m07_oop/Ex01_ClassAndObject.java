package com.learn.m07_oop;

/*
 * ============================================================
 * 模块：m07 面向对象
 * 关卡：Ex01 类与对象
 * ------------------------------------------------------------
 * 【知识点】
 *   类（class）是“模板”，对象（object）是按模板造出来的“实例”。
 *   类里可以有“字段”（保存数据）和“方法”（行为）。
 *       Point p = new Point();   // 用 new 创建一个 Point 对象
 *       p.x = 3;                 // 给对象的字段赋值
 *       p.show();                // 调用对象的方法
 *   下面的 Point 类写在本文件的 public 主类下方（合法）。
 *
 * 【本关任务】
 *   创建好的点 p，给它的 x 赋值 3、y 赋值 4。
 *
 * 【如何闯关】
 *   补全两行赋值语句，运行对照输出。
 * ============================================================
 */
public class Ex01_ClassAndObject {

    public static void main(String[] args) {
        Point p = new Point();

        // TODO(关卡1-1)：给 p.x 赋值 3
        // TODO(关卡1-2)：给 p.y 赋值 4
        //   提示：写法形如  p.x = 3;

        System.out.println("点坐标：(" + p.x + ", " + p.y + ")");
        p.show();
    }
}

// 辅助类：一个简单的“点”。注意它没有 public，和主类写在同一个文件里。
class Point {
    int x; // 字段：横坐标（默认值 0）
    int y; // 字段：纵坐标（默认值 0）

    // 方法：打印自己的位置
    void show() {
        System.out.println("我是一个点，位于 (" + x + ", " + y + ")");
    }
}

