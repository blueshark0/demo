/*
 * ============================================================
 * 模块：m07 面向对象
 * 关卡：Ex01 类与对象
 * ------------------------------------------------------------
 * 【知识点】
 *   类（class）是“模板”，对象（object）是按模板造出来的“实例”。
 *   类里可以有“字段”（保存数据）和“方法”（行为）。用 new 可以按类
 *   创建一个对象；拿到对象后，可以给它的字段赋值，也可以调用它的方法。
 *   一个文件里允许写一个 public 主类，再在主类下方写若干不带 public
 *   的辅助类（本文件下方的 Point 就是这样写的）。
 *
 * 【本关任务】
 *   已经为你创建好一个点对象 p。请给它的 x 字段赋值 3、y 字段赋值 4，
 *   使后续打印结果为「点坐标：(3, 4)」与「我是一个点，位于 (3, 4)」。
 * ============================================================
 */
public class Ex01_ClassAndObject {

    public static void main(String[] args) {
        Point p = new Point();

        // TODO(关卡1-1)：给 p 的 x 字段赋值 3

        // TODO(关卡1-2)：给 p 的 y 字段赋值 4

        System.out.println("点坐标：(" + p.x + ", " + p.y + ")");
        p.show();
    }
}

// 辅助类：一个简单的“点”。注意它没有 public，和主类写在同一个文件里。
class Point {
    int x; // 字段：横坐标（默认值 0）
    int y; // 字段：纵坐标（默认值 0）

    // 方法：打印自己的位置
    void show() {
        System.out.println("我是一个点，位于 (" + x + ", " + y + ")");
    }
}

